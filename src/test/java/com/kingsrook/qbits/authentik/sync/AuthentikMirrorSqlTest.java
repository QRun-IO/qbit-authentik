   /***************************************************************************
    ** Independent connections and thread contexts compete for the same group.
    ***************************************************************************/
   private AuthentikInvitationAssignments.Attempt raceInvitationAttempt(String reference, String group) throws Exception
   {
      var instance = QContext.getQInstance();
      var ready = new java.util.concurrent.CountDownLatch(2);
      var start = new java.util.concurrent.CountDownLatch(1);
      java.util.concurrent.Callable<AuthentikInvitationAssignments.Attempt> task = () ->
      {
         QContext.init(instance, new QSystemUserSession(instance));
         try
         {
            ready.countDown();
            if(!start.await(10, java.util.concurrent.TimeUnit.SECONDS))
            {
               throw (new IllegalStateException("Invitation race did not start."));
            }
            return (new AuthentikInvitationAssignments(config, source::getConnection).begin(reference, group));
         }
         finally
         {
            QContext.clear();
         }
      };
      try(var executor = java.util.concurrent.Executors.newFixedThreadPool(2))
      {
         var first = executor.submit(task);
         var second = executor.submit(task);
         try
         {
            assertThat(ready.await(10, java.util.concurrent.TimeUnit.SECONDS)).isTrue();
         }
         finally
         {
            start.countDown();
         }
         var attempts = java.util.stream.Stream.of(first.get(10, java.util.concurrent.TimeUnit.SECONDS), second.get(10, java.util.concurrent.TimeUnit.SECONDS))
            .filter(java.util.Objects::nonNull).toList();
         assertThat(attempts).hasSize(1);
         return (attempts.getFirst());
      }
   }

   /***************************************************************************
    ** Cancelled, expired or differently scoped intent cannot be revived. A lost
    ** remote response retains IN_FLIGHT across restarts and cannot auto-retry.
    ***************************************************************************/
   @Test
   void invitationIntentRejectsCancellationExpiryAndAmbiguousRetries() throws Exception
   {
      var store = new AuthentikInvitationAssignments(config, source::getConnection);
      String group = UUID.randomUUID().toString();
      String reference = store.create(1, UUID.randomUUID().toString(), "enrollment", "Approved onboarding", List.of(group));
      assertThat(store.cancel(reference)).isTrue();
      assertThat(store.attach(reference, UUID.randomUUID().toString())).isFalse();
      String expired = store.create(1, UUID.randomUUID().toString(), "enrollment", "Approved onboarding", List.of(group));
      sql("UPDATE authentik_invitation_assignment SET expires_at=CURRENT_TIMESTAMP - INTERVAL '1' HOUR WHERE reference='" + expired + "'");
      assertThat(store.attach(expired, UUID.randomUUID().toString())).isFalse();
      assertThat(store.find(expired)).isNotNull();
      assertThat(store.cancel(expired)).isTrue();
      assertThat(store.find(expired).status()).isEqualTo("CANCELLED");
      String pending = store.create(1, UUID.randomUUID().toString(), "enrollment", "Approved onboarding", List.of(group));
      var intent = store.find(pending);
      String invitation = UUID.randomUUID().toString();
      assertThat(store.attach(pending, invitation)).isTrue();
      assertThat(store.findByInvitation(invitation).reference()).isEqualTo(pending);
      var consumed = new com.kingsrook.qbits.authentik.admin.AuthentikInvitationEvidence.Consumption(UUID.randomUUID().toString(), invitation, intent.createdAt());
      var enrolled = new com.kingsrook.qbits.authentik.admin.AuthentikInvitationEvidence.Enrollment(UUID.randomUUID().toString(), pending, 2, intent.createdAt());
      assertThat(store.bind(pending, consumed, enrolled, UUID.randomUUID().toString())).isTrue();
      var attempt = store.begin(pending, group);
      var restarted = new AuthentikInvitationAssignments(config, source::getConnection);
      assertThat(restarted.find(pending).groups()).containsEntry(group, "IN_FLIGHT");
      assertThat(restarted.begin(pending, group)).isNull();
      sql("UPDATE authentik_invitation_assignment SET expires_at=CURRENT_TIMESTAMP - INTERVAL '1' HOUR WHERE reference='" + pending + "'");
      assertThat(store.finish(attempt, false)).isTrue();
      assertThat(restarted.find(pending).status()).isEqualTo("REVIEW");
      assertThat(restarted.begin(pending, group)).isNull();
      config.withPolicyAttribute("qqq.io/changed-policy");
      assertThat(store.find(pending)).isNull();
      assertThat(store.findByInvitation(invitation)).isNull();
      QContext.setQSession(new com.kingsrook.qqq.backend.core.model.session.QSession());
      assertThatThrownBy(() -> store.find(reference)).isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
   }

