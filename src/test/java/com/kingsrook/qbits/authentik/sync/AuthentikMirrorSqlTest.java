   /*******************************************************************************
    ** Isolated host database, production mirror migration, standard QQQ audits.
    *******************************************************************************/
   @BeforeEach
   void setUp() throws Exception
   {
      String owner = "mirror_" + UUID.randomUUID().toString().replace("-", "");
      source = createSource(owner);
      config = AuthentikTestSupport.unitConfig();
      QInstance instance = AuthentikTestSupport.produce(config);
      config.withLocalBackendName(owner);
      instance.addBackend(backend(owner, source));
      for(var table : AuthentikSyncTables.all(config))
      {
         enrich(table);
         instance.addTable(table);
      }
      List<QTableMetaData> auditTables = new ArrayList<>();
      new AuditsMetaDataProvider().withDefineRecordScreens(false).defineAll(instance, owner, table ->
      {
         enrich(table);
         auditTables.add(table);
      });
      try(var connection = source.getConnection(); var statement = connection.createStatement())
      {
         statement.execute(Files.readString(Path.of("docs/schema-sync.sql")));
         for(var table : auditTables)
         {
            List<String> columns = new ArrayList<>();
            for(var field : table.getFields().values())
            {
               String type = switch(field.getType())
               {
                  case INTEGER -> "INTEGER";
                  case LONG -> "BIGINT";
                  case DATE_TIME -> "TIMESTAMP WITH TIME ZONE";
                  default -> "VARCHAR(4096)";
               };
               columns.add(field.getBackendName() + " " + type + (field.getName().equals("id") ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : ""));
            }
            statement.execute("CREATE TABLE " + snake(table.getName()) + " (" + String.join(",", columns) + ")");
         }
      }
      QContext.init(instance, new QSystemUserSession(instance));
      writer = new AuthentikMirrorWriter(config);
   }

