   /*******************************************************************************
    ** Rollback removes both mirror and audit writes; commit exposes both.
    *******************************************************************************/
   @Test
   void mirrorAndAuditUseOneTransaction() throws Exception
   {
      try(var transaction = new RDBMSTransaction(source.getConnection()))
      {
         writer.fullRefresh(snapshot("sam", "jo"), transaction);
         assertThat(count("authentik_user_mirror")).isZero();
         assertThat(count("audit")).isZero();
         transaction.rollback();
      }
      assertThat(count("authentik_user_mirror")).isZero();
      assertThat(count("audit")).isZero();
      try(var transaction = new RDBMSTransaction(source.getConnection()))
      {
         writer.fullRefresh(snapshot("sam", "jo"), transaction);
         transaction.commit();
      }
      assertThat(count("authentik_user_mirror")).isEqualTo(2);
      assertThat(count("audit")).isEqualTo(2);
   }

   /*******************************************************************************
    ** Swap two unique usernames and emails without losing either local ID.
    ** Another connection cannot observe the temporary reservation names.
    *******************************************************************************/
   @Test
   void uniqueIdentitySwapsAreAtomicAndKeepIds() throws Exception
   {
      try(var transaction = new RDBMSTransaction(source.getConnection()))
      {
         writer.fullRefresh(snapshot("sam", "jo"), transaction);
         transaction.commit();
      }
      int firstId;
      try(var connection = source.getConnection(); var statement = connection.createStatement();
         var result = statement.executeQuery("SELECT id FROM authentik_user_mirror WHERE pk=1"))
      {
         result.next();
         firstId = result.getInt(1);
      }
      try(var transaction = new RDBMSTransaction(source.getConnection()))
      {
         writer.fullRefresh(snapshot("jo", "sam"), transaction);
         try(var connection = source.getConnection(); var statement = connection.createStatement();
            var result = statement.executeQuery("SELECT username FROM authentik_user_mirror WHERE pk=1"))
         {
            result.next();
            assertThat(result.getString(1)).isEqualTo("sam");
         }
         transaction.commit();
      }
      try(var connection = source.getConnection(); var statement = connection.createStatement();
         var result = statement.executeQuery("SELECT id,username,email FROM authentik_user_mirror WHERE pk=1"))
      {
         result.next();
         assertThat(result.getInt(1)).isEqualTo(firstId);
         assertThat(result.getString(2)).isEqualTo("jo");
         assertThat(result.getString(3)).isEqualTo("jo@example.test");
      }
      assertThat(count("audit")).isEqualTo(6);
   }

   /*******************************************************************************
    ** Competing host processes share a single durable directory ownership row.
    ** Expired workers cannot renew, publish or release the replacement's lease.
    *******************************************************************************/
   @Test
   void directoryLeaseSerializesAndFencesWorkers() throws Exception
   {
      var lease = new AuthentikSyncLease(source::getConnection, config, java.time.Duration.ofMinutes(5));
      List<AuthentikSyncLease.Claim> winners = new ArrayList<>();
      try(var pool = java.util.concurrent.Executors.newFixedThreadPool(4))
      {
         List<java.util.concurrent.Callable<AuthentikSyncLease.Claim>> attempts = new ArrayList<>();
         for(int i = 0; i < 8; i++)
         {
            attempts.add(lease::acquire);
         }
         for(var result : pool.invokeAll(attempts))
         {
            var claim = result.get();
            if(claim != null)
            {
               winners.add(claim);
            }
         }
      }
      assertThat(winners).hasSize(1);
      var original = winners.getFirst();
      sql("UPDATE authentik_sync_state SET lease_until=TIMESTAMP '2000-01-01 00:00:00'");
      assertThat(lease.renew(original)).isFalse();
      var replacement = lease.acquire();
      assertThat(replacement).isNotNull();
      lease.release(original);
      try(var transaction = new RDBMSTransaction(source.getConnection()))
      {
         assertThat(lease.lock(transaction.getConnection(), original)).isFalse();
         assertThat(lease.complete(transaction.getConnection(), original, true)).isFalse();
         transaction.rollback();
      }
      assertThat(lease.renew(replacement)).isTrue();
      try(var transaction = new RDBMSTransaction(source.getConnection()))
      {
         assertThat(lease.complete(transaction.getConnection(), replacement, true)).isTrue();
         transaction.rollback();
      }
      assertThat(lease.acquire()).isNull();
      try(var transaction = new RDBMSTransaction(source.getConnection()))
      {
         assertThat(lease.complete(transaction.getConnection(), replacement, true)).isTrue();
         transaction.commit();
      }
      var next = lease.acquire();
      assertThat(next.watermark()).isEqualTo(replacement.startedAt());
      lease.release(next);
   }

