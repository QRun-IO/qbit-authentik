   /*******************************************************************************
    ** Bindings survive a new reader/node and never reassign identity or extend
    ** the original login lifetime when a duplicate creation arrives.
    *******************************************************************************/
   @Test
   void sessionBindingIsWriteOnceAndNeverStoresTheCookie() throws Exception
   {
      var first = new AuthentikSessionBindings(config);
      var otherNode = new AuthentikSessionBindings(config, source::getConnection);
      String cookie = UUID.randomUUID().toString();
      Instant deadline = Instant.now().plusSeconds(3600).truncatedTo(java.time.temporal.ChronoUnit.MILLIS);
      var binding = new AuthentikSessionBindings.Binding(1, "source-uuid", "sam@example.test", deadline);
      assertThat(first.find(cookie)).isNull();
      assertThat(first.bind(cookie, binding)).isEqualTo(binding);
      assertThat(otherNode.find(cookie.toUpperCase(java.util.Locale.ROOT))).isEqualTo(binding);
      assertThat(scalar("SELECT session_hash FROM authentik_session_binding")).hasSize(64).isNotEqualTo(cookie);
      assertThat(first.bind(cookie, new AuthentikSessionBindings.Binding(1, "source-uuid", "sam@example.test", deadline.plusSeconds(3600))))
         .isEqualTo(binding);
      for(var replacement : List.of(new AuthentikSessionBindings.Binding(2, "other-uuid", "sam@example.test", deadline),
         new AuthentikSessionBindings.Binding(1, "other-uuid", "sam@example.test", deadline),
         new AuthentikSessionBindings.Binding(1, "source-uuid", "renamed@example.test", deadline)))
      {
         assertThatThrownBy(() -> otherNode.bind(cookie, replacement))
            .isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
      }
      String baseUrl = config.getBaseUrl();
      config.withBaseUrl("https://other.example.test");
      assertThat(new AuthentikSessionBindings(config).find(cookie)).isNull();
      assertThat(first.find(cookie)).isNull();
      config.withBaseUrl(baseUrl);
      sql("UPDATE authentik_session_binding SET expires_at=CURRENT_TIMESTAMP - INTERVAL '1' HOUR");
      assertThat(otherNode.find(cookie)).isNull();
      assertThatThrownBy(() -> first.bind(cookie, binding))
         .isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
      assertThat(first.purgeExpired()).isZero();
      sql("UPDATE authentik_session_binding SET expires_at=CURRENT_TIMESTAMP - INTERVAL '31' DAY");
      assertThat(first.purgeExpired()).isEqualTo(1);
   }

   /*******************************************************************************
    ** Revocation is durable even before initial binding; missing/expired session
    ** storage must not be repopulated by the authentication resume path.
    *******************************************************************************/
   @Test
   void sessionBindingRevocationPreventsLateCreationAndUntrustedAccess() throws Exception
   {
      var store = new AuthentikSessionBindings(config);
      var binding = new AuthentikSessionBindings.Binding(1, "source-uuid", "sam@example.test", Instant.now().plusSeconds(3600));
      String beforeLogin = UUID.randomUUID().toString();
      store.revoke(beforeLogin);
      store.revoke(beforeLogin);
      assertThat(store.find(beforeLogin)).isNull();
      assertThatThrownBy(() -> store.bind(beforeLogin, binding))
         .isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
      String afterLogin = UUID.randomUUID().toString();
      store.bind(afterLogin, binding);
      store.revoke(afterLogin);
      assertThat(store.find(afterLogin)).isNull();
      assertThatThrownBy(() -> store.bind(afterLogin, binding))
         .isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
      assertThatThrownBy(() -> store.find("not-a-cookie")).isInstanceOf(IllegalArgumentException.class)
         .hasMessageNotContaining("not-a-cookie");
      assertThatThrownBy(() -> store.bind(UUID.randomUUID().toString(),
         new AuthentikSessionBindings.Binding(1, "uuid", "user", Instant.EPOCH))).isInstanceOf(IllegalArgumentException.class);
      assertThat(count("authentik_session_binding")).isEqualTo(2);
      QContext.setQSession(new com.kingsrook.qqq.backend.core.model.session.QSession());
      assertThatThrownBy(() -> store.find(afterLogin)).isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
      assertThatThrownBy(() -> store.bind(afterLogin, binding)).isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
      assertThatThrownBy(() -> store.revoke(afterLogin)).isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
      assertThatThrownBy(store::purgeExpired).isInstanceOf(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException.class);
   }

   /*******************************************************************************
    ** Real simultaneous creators, separate connections and contexts: exactly
    ** one principal can claim a session identifier, including across nodes.
    *******************************************************************************/
   @Test
   void concurrentSessionBindingsCannotReassignTheWinner() throws Exception
   {
      String cookie = UUID.randomUUID().toString();
      var instance = QContext.getQInstance();
      var ready = new java.util.concurrent.CountDownLatch(2);
      try(var threads = java.util.concurrent.Executors.newFixedThreadPool(2))
      {
         var attempts = new java.util.ArrayList<java.util.concurrent.Future<Boolean>>();
         for(int id : List.of(1, 2))
         {
            attempts.add(threads.submit(() ->
            {
               QContext.init(instance, new QSystemUserSession(instance));
               try
               {
                  ready.countDown();
                  if(!ready.await(5, java.util.concurrent.TimeUnit.SECONDS))
                  {
                     throw (new IllegalStateException("Concurrent creators did not start."));
                  }
                  new AuthentikSessionBindings(config, source::getConnection).bind(cookie,
                     new AuthentikSessionBindings.Binding(id, "uuid-" + id, "user-" + id, Instant.now().plusSeconds(3600)));
                  return (true);
               }
               catch(com.kingsrook.qqq.backend.core.exceptions.QPermissionDeniedException expectedLoser)
               {
                  return (false);
               }
               finally
               {
                  QContext.clear();
               }
            }));
         }
         assertThat(List.of(attempts.get(0).get(10, java.util.concurrent.TimeUnit.SECONDS),
            attempts.get(1).get(10, java.util.concurrent.TimeUnit.SECONDS))).containsExactlyInAnyOrder(true, false);
      }
      assertThat(count("authentik_session_binding")).isEqualTo(1);
      assertThat(new AuthentikSessionBindings(config).find(cookie)).isNotNull();
   }
