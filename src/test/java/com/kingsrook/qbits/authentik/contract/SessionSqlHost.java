package com.kingsrook.qbits.authentik.contract;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import com.kingsrook.qbits.authentik.AuthentikQBitConfig;
import com.kingsrook.qbits.authentik.client.AuthentikActionUtil;
import com.kingsrook.qbits.authentik.sync.AuthentikMirrorWorker;
import com.kingsrook.qbits.authentik.sync.AuthentikSyncTables;
import com.kingsrook.qqq.backend.core.context.QContext;
import com.kingsrook.qqq.backend.core.model.audits.AuditsMetaDataProvider;
import com.kingsrook.qqq.backend.core.model.metadata.QInstance;
import com.kingsrook.qqq.backend.core.model.metadata.tables.QTableMetaData;
import com.kingsrook.qqq.backend.core.model.session.QSystemUserSession;
import com.kingsrook.qqq.backend.module.rdbms.model.metadata.RDBMSBackendMetaData;
import com.kingsrook.qqq.backend.module.rdbms.model.metadata.RDBMSTableBackendDetails;
import org.h2.jdbcx.JdbcDataSource;

/*******************************************************************************
 ** Real host SQL mirrors/bindings for live-provider authentication contracts.
 ** Existing unrelated bookkeeping tables keep their original test backend.
 ******************************************************************************/
final class SessionSqlHost implements AutoCloseable
{
   private final JdbcDataSource source = new JdbcDataSource();
   private final QInstance instance;
   private final AuthentikQBitConfig config;

   /***************************************************************************
    ** Add uniquely owned SQL storage and real QQQ audit tables to the host.
    ***************************************************************************/
   SessionSqlHost(QInstance instance, AuthentikQBitConfig config) throws Exception
   {
      this(instance, config, false);
   }

   /***************************************************************************
    ** Invitation contracts also persist the administrative action audit in SQL.
    ***************************************************************************/
   SessionSqlHost(QInstance instance, AuthentikQBitConfig config, boolean includeAdminTables) throws Exception
   {
      this.instance = instance;
      this.config = config;
      String owner = "session_contract_" + UUID.randomUUID().toString().replace("-", "");
      source.setURL("jdbc:h2:mem:" + owner + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
      source.setUser("sa");
      source.setPassword("");
      config.withLocalBackendName(owner);
      instance.addBackend(new RDBMSBackendMetaData().withName(owner).withVendor(RDBMSBackendMetaData.VENDOR_H2)
         .withJdbcUrl(source.getURL()).withUsername("sa").withPassword(""));
      for(var table : AuthentikSyncTables.all(config))
      {
         enrich(table);
         instance.addTable(table);
      }
      List<QTableMetaData> audits = new ArrayList<>();
      new AuditsMetaDataProvider().withDefineRecordScreens(false).defineAll(instance, owner, table ->
      {
         enrich(table);
         audits.add(table);
      });
      if(includeAdminTables)
      {
         for(String name : List.of(com.kingsrook.qbits.authentik.admin.AuthentikLocalTables.ADMIN_ACTION,
            com.kingsrook.qbits.authentik.admin.AuthentikLocalTables.APPROVAL_REQUEST))
         {
            var table = instance.getTable(config.applyTablePrefix(name));
            table.setBackendName(owner);
            enrich(table);
            audits.add(table);
         }
      }
      try(var connection = source.getConnection(); var statement = connection.createStatement())
      {
         statement.execute(Files.readString(Path.of("docs/schema-sync.sql")));
         for(var table : audits)
         {
            List<String> columns = new ArrayList<>();
            for(var field : table.getFields().values())
            {
               String type = switch(field.getType())
               {
                  case INTEGER -> "INTEGER";
                  case LONG -> "BIGINT";
                  case DATE_TIME -> "TIMESTAMP WITH TIME ZONE";
                  default -> "VARCHAR(4096)";
               };
               columns.add(field.getBackendName() + " " + type + (field.getName().equals("id") ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : ""));
            }
            statement.execute("CREATE TABLE " + snake(table.getName()) + " (" + String.join(",", columns) + ")");
         }
      }
   }

   /***************************************************************************
    ** Read one fixture-owned SQL value without exposing provider bodies.
    ***************************************************************************/
   String scalar(String sql) throws Exception
   {
      try(var connection = source.getConnection(); var statement = connection.createStatement(); var result = statement.executeQuery(sql))
      {
         if(!result.next())
         {
            throw (new IllegalStateException("Expected fixture row is missing."));
         }
         return (result.getString(1));
      }
   }

   /***************************************************************************
    ** Publish actual Authentik directory changes through the production worker.
    ***************************************************************************/
   boolean reconcile() throws Exception
   {
      var previous = QContext.capture();
      try
      {
         QContext.init(instance, new QSystemUserSession(instance));
         return (new AuthentikMirrorWorker(config, AuthentikActionUtil.forBackend(config.getApiBackendName()))
            .fullRefresh((snapshot, transaction) -> { }, null, null));
      }
      finally
      {
         QContext.init(previous);
      }
   }

   /***************************************************************************
    ** Map the production migration's physical column/table names.
    ***************************************************************************/
   private static void enrich(QTableMetaData table)
   {
      table.withBackendDetails(new RDBMSTableBackendDetails().withTableName(snake(table.getName())));
      table.getFields().values().forEach(field -> field.setBackendName(snake(field.getName())));
   }

   /***************************************************************************
    ** Same physical naming convention as the host migration.
    ***************************************************************************/
   private static String snake(String name)
   {
      return (name.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase(java.util.Locale.ROOT));
   }

   /***************************************************************************
    ** Drop only this fixture's isolated in-memory database.
    ***************************************************************************/
   @Override
   public void close() throws Exception
   {
      try(var connection = source.getConnection(); var statement = connection.createStatement())
      {
         statement.execute("DROP ALL OBJECTS");
      }
   }
}
