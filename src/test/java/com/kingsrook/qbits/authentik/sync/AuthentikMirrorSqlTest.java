   /*******************************************************************************
    ** Session-marker failure rolls back mirror/audit/checkpoint. Successful
    ** publication invokes QQQ after-commit callbacks after data is visible.
    *******************************************************************************/
   @Test
   void workerCommitsOrRollsBackWholePublication() throws Exception
   {
      var worker = worker();
      var callbacks = new java.util.concurrent.atomic.AtomicInteger();
      assertThatThrownBy(() -> worker.fullRefresh((snapshot, transaction) ->
      {
         transaction.addAfterCommitCallback(callbacks::incrementAndGet);
         throw (new IllegalStateException("synthetic marker failure"));
      }, null, null)).isInstanceOf(IllegalStateException.class);
      assertThat(count("authentik_user_mirror")).isZero();
      assertThat(count("audit")).isZero();
      assertThat(callbacks.get()).isZero();
      assertThat(count("authentik_sync_state WHERE watermark IS NOT NULL")).isZero();
      assertThat(worker.fullRefresh((snapshot, transaction) ->
      {
         assertThat(count("authentik_user_mirror")).isZero();
         transaction.addAfterCommitCallback(callbacks::incrementAndGet);
      }, null, null)).isTrue();
      assertThat(count("authentik_user_mirror")).isEqualTo(1);
      assertThat(count("audit")).isEqualTo(1);
      assertThat(callbacks.get()).isEqualTo(1);
      assertThat(count("authentik_sync_state WHERE watermark IS NOT NULL AND last_full_sync IS NOT NULL")).isEqualTo(1);
   }

