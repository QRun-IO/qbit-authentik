package com.kingsrook.qbits.authentik.contract;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.UUID;
import com.kingsrook.qqq.backend.core.model.metadata.QInstance;
import com.kingsrook.qqq.backend.core.model.metadata.tables.QTableMetaData;
import com.kingsrook.qqq.backend.module.rdbms.model.metadata.RDBMSBackendMetaData;
import com.kingsrook.qqq.backend.module.rdbms.model.metadata.RDBMSTableBackendDetails;
import org.h2.jdbcx.JdbcDataSource;

/*******************************************************************************
 ** Private disposable SQL database for the manual review host. Apply the actual
 ** QBit migrations; standard QQQ audit tables follow their host metadata.
 *******************************************************************************/
final class ReviewSqlDatabase
{
   static final String BACKEND = "reviewIdentity";
   private final JdbcDataSource source = new JdbcDataSource();
   private final ArrayList<QTableMetaData> audits = new ArrayList<>();

   /***************************************************************************
    ** Register host storage before producing the QBit and its scheduled jobs.
    ***************************************************************************/
   ReviewSqlDatabase(QInstance instance) throws com.kingsrook.qqq.backend.core.exceptions.QException
   {
      source.setURL("jdbc:h2:mem:qbit_review_" + UUID.randomUUID().toString().replace("-", "") + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
      source.setUser("sa");
      source.setPassword("");
      instance.addBackend(new RDBMSBackendMetaData().withName(BACKEND).withVendor(RDBMSBackendMetaData.VENDOR_H2)
         .withJdbcUrl(source.getURL()).withUsername("sa").withPassword(""));
      new com.kingsrook.qqq.backend.core.model.audits.AuditsMetaDataProvider().withDefineRecordScreens(false)
         .defineAll(instance, BACKEND, audits::add);
   }

   /***************************************************************************
    ** Match physical names and create only this JVM's private schema.
    ***************************************************************************/
   void initialize(QInstance instance) throws Exception
   {
      instance.getTables().values().stream().filter(table -> BACKEND.equals(table.getBackendName())).forEach(table ->
      {
         table.withBackendDetails(new RDBMSTableBackendDetails().withTableName(snake(table.getName())));
         table.getFields().values().forEach(field ->
         {
            if(field.getBackendName() == null)
            {
               field.setBackendName(snake(field.getName()));
            }
         });
      });
      try(var connection = source.getConnection(); var statement = connection.createStatement())
      {
         statement.execute(Files.readString(Path.of("docs/schema.sql")));
         statement.execute(Files.readString(Path.of("docs/schema-sync.sql")));
         for(var table : audits)
         {
            var columns = new ArrayList<String>();
            for(var field : table.getFields().values())
            {
               String type = switch(field.getType())
               {
                  case INTEGER -> "INTEGER";
                  case LONG -> "BIGINT";
                  case BOOLEAN -> "BOOLEAN";
                  case DATE_TIME -> "TIMESTAMP WITH TIME ZONE";
                  default -> "TEXT";
               };
               columns.add(field.getBackendName() + " " + type + (field.getName().equals("id") ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : ""));
            }
            statement.execute("CREATE TABLE " + snake(table.getName()) + " (" + String.join(",", columns) + ")");
         }
      }
   }

   /***************************************************************************
    ** Physical convention shared by the published SQL migrations.
    ***************************************************************************/
   private static String snake(String value)
   {
      return (value.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase(java.util.Locale.ROOT));
   }
}
