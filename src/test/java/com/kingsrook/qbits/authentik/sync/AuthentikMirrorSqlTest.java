      config.withSchedulerName("freshness-contract");
      var schedule = AuthentikSyncProcesses.processes(QContext.getQInstance(), config).stream()
         .filter(process -> process.getName().equals(config.applyPrefix(AuthentikSyncProcesses.INCREMENTAL)))
         .findFirst().orElseThrow().getSchedule();
      var reader = new AuthentikMirrorAccess(config, Duration.ofMinutes(15));
      String uuid = "81000000-0000-0000-0000-000000000001";
      ageAuthorizationSnapshot(Duration.ofSeconds(schedule.getRepeatSeconds()).plusMinutes(4));
      assertThat(reader.read(1, uuid).status()).as("previous publication remains usable while the next scan finishes")
         .isEqualTo(AuthentikMirrorAccess.Status.READY);
